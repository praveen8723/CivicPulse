export function translateInterface(input: string): string {
  const leading = input.match(/^\s*/)?.[0] ?? "";
  const trailing = input.match(/\s*$/)?.[0] ?? "";
  const source = input.trim();
  if (!source) return input;
  const exact = kannada[source] ?? moreKannada[source] ?? homeKannada[source];
  if (exact) return `${leading}${exact}${trailing}`;
  for (const [pattern, translate] of patterns) {
    const match = source.match(pattern);
    if (match) return `${leading}${translate(...match.slice(1))}${trailing}`;
  }
  if (
    /^\d{1,2} (?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)\b/.test(
      source,
    )
  ) {
    const dated = source.replace(
      /\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Sept|Oct|Nov|Dec)\b/g,
      (month) => months[month],
    );
    return `${leading}${dated}${trailing}`;
  }
  return input;
}
